export const getBigOverlayLine = (
  characterId: string,
  eventKey: string | undefined,
  type: "surge" | "bonk" | "lead" | "close",
  replacements: Record<string, string>
) => {
  const characterLines = BIG_OVERLAY_LINES[characterId];
  const direct = eventKey && characterLines ? characterLines[eventKey] : undefined;
  const fallback = BIG_OVERLAY_LINES.generic[type] || [];
  const pool = direct && direct.length > 0 ? direct : fallback;
  const template = pool[Math.floor(Math.random() * pool.length)] ?? "";

  return Object.entries(replacements).reduce((acc, [key, value]) => {
    return acc.replace(new RegExp(`\\{${key}\\}`, "g"), value);
  }, template);
};
